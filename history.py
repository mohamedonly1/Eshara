# -*- coding: utf-8 -*-
"""
أهلاً بك يا صديقي! في هذا الملف سنتعلم كيف ندير "سجل عمليات المستخدم" أو (History Log).

تخيل أن المستخدم في تطبيقنا يقوم بترجمة كلمات أو جمل بلغة الإشارة، ونحن نريد أن نوفر له ميزة 
سجل الكلمات السابقة لكي يعود إليها متى يشاء، أو يحذف كلمة منها.
هذا الملف (history.py) هو المسؤول عن هذه المهمة تماماً: يقرأ، ويضيف، ويحذف السجلات لكل مستخدم بشكل مستقل.

دعنا نستكشف كيف يعمل الكود ببساطة:
"""

import json      # مكتبة للتعامل مع صيغة البيانات JSON، وهي الطريقة التي نحفظ بها السجل على شكل نص منظم
import os        # مكتبة للتعامل مع نظام التشغيل، مثل إنشاء المجلدات والتأكد من وجود الملفات
import uuid      # مكتبة لإنشاء معرفات فريدة وعشوائية (Unique IDs) لكي نميز كل جملة مسجلة بمعرف خاص بها
from datetime import datetime  # مكتبة لمعرفة التاريخ والوقت الحالي وتنسيقهما بشكل جميل

import config

# نحدد المجلد الذي سنخزن فيه ملفات سجلات المستخدمين
HISTORY_DIR = config.USERS_DIR

def _path(user_id):
    """
    هذه دالة مساعدة داخلية (تبدأ بشرطة سفلية _ للدلالة على أنها للاستخدام الداخلي فقط).
    مهمتها تحديد المسار الدقيق لملف السجل الخاص بالمستخدم بناءً على اسمه أو معرفه.
    مثلاً: إذا كان اسم المستخدم 'mohamed'، فسترجع المسار: 'users_data/mohamed_history.json'
    """
    return os.path.join(HISTORY_DIR, f'{user_id}_history.json')

def get_entries(user_id):
    """
    هذه الدالة تستدعى عندما نريد جلب (قراءة) قائمة الكلمات والجمل التي ترجمها المستخدم سابقاً.
    """
    path = _path(user_id)
    
    # إذا لم يكن لدى المستخدم سجل سابق (مثلاً مستخدم جديد تماماً)، نرجع قائمة فارغة []
    if not os.path.exists(path):
        return []
    
    # إذا كان الملف موجوداً، نقوم بفتحه وقراءة محتوياته وتحويلها من نص JSON إلى قائمة بايثون ونرجعها
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def save_entry(user_id, text):
    """
    هذه الدالة تستدعى لحفظ جملة أو كلمة جديدة ترجمها المستخدم في السجل الخاص به.
    """
    # 1. نجلب السجلات الحالية للمستخدم أولاً
    entries = get_entries(user_id)
    
    # 2. نضيف السجل الجديد في بداية القائمة (الموقع 0) لكي يظهر أولاً للمستخدم (من الأحدث للأقدم)
    entries.insert(0, {
        'id': uuid.uuid4().hex[:16],  # ننشئ معرفاً عشوائياً فريداً طوله 16 حرفاً
        'text': text,                 # النص الذي تمت ترجمته
        'time': datetime.now().strftime('%Y-%m-%d %H:%M'),  # وقت التسجيل الحالي
        'date': datetime.now().strftime('%Y-%m-%d')        # تاريخ التسجيل الحالي
    })
    
    # 3. حتى لا يمتلئ الهارد ديسك بالبيانات، سنحتفظ بآخر 100 عملية ترجمة فقط لكل مستخدم
    # الرمز [:100] يعني "خذ العناصر من البداية وحتى العنصر رقم 100 فقط"
    entries = entries[:100]
    
    # 4. نتأكد أن مجلد الحفظ موجود، وإذا لم يكن موجوداً نقوم بإنشائه تلقائياً
    os.makedirs(HISTORY_DIR, exist_ok=True)
    
    # 5. نفتح ملف المستخدم ونكتب القائمة المحدثة بالكامل بصيغة JSON مقروءة وجميلة
    with open(_path(user_id), 'w', encoding='utf-8') as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)

def delete_entry(user_id, entry_id):
    """
    هذه الدالة تستدعى عندما يريد المستخدم حذف جملة معينة من سجله.
    """
    # 1. نجلب السجلات الحالية للمستخدم
    entries = get_entries(user_id)
    
    # 2. نقوم بفلترة القائمة: نأخذ كل السجلات ونستبعد السجل الذي يتطابق معرفه (id) مع المعرف المراد حذفه (entry_id)
    entries = [e for e in entries if e.get('id') != entry_id]
    
    # 3. نحفظ القائمة الجديدة بعد الفلترة في ملف المستخدم مرة أخرى
    with open(_path(user_id), 'w', encoding='utf-8') as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)
